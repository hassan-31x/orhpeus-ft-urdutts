"""Reclaim reproducible converted WAVs after complete, verified SNAC encoding."""
import csv
import logging
from pathlib import Path
import random
import re
import shutil

from orpheus_utils import atomic_json, contained, fingerprint, read_json, sha256
from pipeline_recovery import valid_chunk

LOG = logging.getLogger("orpheus_urdu")


def release_encoded_audio(root, cache, run, cfg):
    """Delete only registered, unchanged generated WAVs; preserve reference clips.

    No deletion occurs until both partitions' token chunks and retained coverage
    are verified. Metadata, Parquet/Arrow caches, model files and checkpoints stay.
    Missing WAVs are regenerated by the existing pinned-source loader on restart.
    """
    import pandas as pd
    root, cache, run = Path(root).resolve(), Path(cache).resolve(), Path(run)
    source = read_json(root / "dataset_source.json")
    recipe = source["recipe"]
    expected = Path(cfg["work_dir"]).resolve() / "datasets" / fingerprint(recipe)
    if root != expected or recipe["dataset_id"] != cfg["dataset_id"] or recipe["revision"] != cfg["dataset_revision"]:
        raise RuntimeError("Audio cleanup requires this run's generated, pinned dataset directory")
    normalized = read_json(run / "normalized_manifests.json")
    retained = read_json(run / "training_manifests.json")
    token_format = read_json(run / "token_format.json")
    for split in ("train", "validation"):
        rows = normalized[split]
        if not rows or fingerprint(rows) != token_format["splits"][split]:
            raise RuntimeError(f"Audio cleanup refused: {split} audit/token identity mismatch")
        accepted = []
        for start in range(0, len(rows), cfg["chunk_size"]):
            subset = rows[start:start + cfg["chunk_size"]]
            path = cache / split / f"{start:07d}.parquet"
            if not valid_chunk(path, path.with_suffix(".json"), fingerprint(subset), len(subset), pd.read_parquet):
                raise RuntimeError(f"Audio cleanup refused: incomplete or corrupt token chunk {path}")
            accepted.extend(pd.read_parquet(path, columns=["audio"])["audio"].tolist())
        if not accepted or accepted != [r["audio"] for r in retained[split]]:
            raise RuntimeError(f"Audio cleanup refused: {split} retained token coverage mismatch")

    # Match notebook reference playback and the Trainer's seeded monitoring prompts.
    keep = set()
    for split in source["splits"]:
        with (root / f"{split}.csv").open(encoding="utf-8", newline="") as handle:
            import itertools
            keep.update(r["audio"] for r in itertools.islice(csv.DictReader(handle), 3))
    validation = retained["validation"]
    keep.update(row["audio"] for row in random.Random(cfg["seed"]).sample(
        validation, min(cfg["sample_count"], len(validation))))

    # Construct the full safe deletion plan first. Never glob-delete an audio folder.
    registered = {}
    for marker in sorted((root / "parts").glob("*.json")):
        part = read_json(marker)
        if part["identity"]["recipe"] != root.name:
            raise RuntimeError("Audio cleanup refused: conversion registry identity mismatch")
        for row in part["rows"]:
            relative = row["audio"]
            if not re.fullmatch(r"audio/(train|validation|test)/\d{5}-\d{6}\.wav", relative):
                raise RuntimeError("Audio cleanup refused: unexpected generated WAV path")
            if relative in registered:
                raise RuntimeError("Audio cleanup refused: duplicate conversion registry entry")
            registered[relative] = row["sha256"]
    audited = {row["audio"] for rows in normalized.values() for row in rows}
    if not audited <= registered.keys():
        raise RuntimeError("Audio cleanup refused: incomplete conversion registry")
    candidates, changed = [], []
    for relative, digest in registered.items():
        path = contained(root, relative)
        if relative in keep or not path.is_file():
            continue
        if sha256(path) != digest:
            changed.append(relative)  # Never delete a file changed since conversion.
            continue
        candidates.append((path, path.stat().st_size))
    # Persist the plan before unlinking; interrupted cleanup is safe to repeat.
    report = dict(dataset_root=str(root), token_cache=str(cache),
                  verified_partitions=["train", "validation"], protected_audio=sorted(keep),
                  preserved_changed_audio=changed, planned_files=len(candidates),
                  planned_bytes=sum(size for _, size in candidates), removed_files=0, removed_bytes=0,
                  status="planned", reason="SNAC encoding complete; WAVs can be regenerated from pinned Hub source")
    atomic_json(run / "audio_storage.json", report)
    for path, size in candidates:
        path.unlink()
        report["removed_files"] += 1
        report["removed_bytes"] += size
    report.update(status="complete", free_bytes=shutil.disk_usage(root).free)
    atomic_json(run / "audio_storage.json", report)
    LOG.info("Reclaimed %.2f GiB from %d converted WAVs; kept %d reference paths; %.2f GiB free",
             report["removed_bytes"] / 2**30, report["removed_files"], len(keep), report["free_bytes"] / 2**30)
    return report
